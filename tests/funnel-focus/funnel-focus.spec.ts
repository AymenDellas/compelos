test('Read page retains onboarding answers on provider failure and allows a reviewed retry', async ({ page }) => {
  let calls = 0;
  await page.route('**/api/copy-studio/import', route => {
    expect(route.request().postDataJSON().url).toBe('https://www.lisahack.com/');
    calls++;
    return calls === 1
      ? route.fulfill({ status: 503, json: { error: 'The configured AI model has no available route on this AgentRouter account. Check COPY_STUDIO_MODEL against the account’s available models. Retrying the same model will not resolve this.' } })
      : route.fulfill({ json: imported });
  });
  await page.goto('/?prep');
  const before = await page.evaluate(() => JSON.stringify((window as any).qaPrepared));
  await page.getByRole('button', { name: 'Read the current website' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Page URL', { exact: true }).fill('https://www.lisahack.com/');
  await dialog.getByRole('button', { name: 'Read page and prefill' }).click();
  await expect(dialog.getByRole('alert')).toContainText('model has no available route');
  await expect(dialog.getByLabel('Page URL', { exact: true })).toHaveValue('https://www.lisahack.com/');
  expect(await page.evaluate(() => JSON.stringify((window as any).qaPrepared))).toBe(before);
  await dialog.getByRole('button', { name: 'Read page and prefill' }).click();
  await expect(dialog.getByText('Recommended: Practice-wide')).toBeVisible();
  expect(calls).toBe(2);
  expect(await page.evaluate(() => JSON.stringify((window as any).qaPrepared))).toBe(before);
});
